namespace WebwareTest\Router;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;
use Psr\Http\Server\MiddlewareInterface;
use Webware\Router\QueryParamRoute;

#[CoversClass(QueryParamRoute::class)]
class QueryParamRouteTest extends TestCase
{
    private MiddlewareInterface $middleware;

    #[Test]
    public function allowsAnyMethodWhenNotSpecified(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action'],
        );

        static::assertTrue($route->allowsAnyMethod());
        static::assertTrue($route->allowsMethod('GET'));
        static::assertTrue($route->allowsMethod('POST'));
        static::assertTrue($route->allowsMethod('DELETE'));
    }

    #[Test]
    public function autoGeneratedNameIncludesQueryParamKeys(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
        );

        static::assertSame('/api?action&type', $route->getName());
    }

    #[Test]
    public function autoGeneratedNameIncludesValueConstraints(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action' => 'profile', 'u' => null],
        );

        // Name should show value constraint for action but not u
        static::assertSame('/api?action=profile&u', $route->getName());
    }

    #[Test]
    public function autoGeneratedNameWithHttpMethod(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action'],
            ['GET', 'POST'],
        );

        static::assertSame('/api?action^GET:POST', $route->getName());
    }

    #[Test]
    public function autoGeneratedNameWithHttpMethodAndMultipleQueryParams(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
            ['GET'],
        );

        static::assertSame('/api?action&type^GET', $route->getName());
    }

    #[Test]
    public function autoGeneratedNameWithoutQueryParams(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            [],
        );

        static::assertSame('/api', $route->getName());
    }

    #[Test]
    public function autoGeneratedNameWithSingleQueryParam(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action'],
        );

        static::assertSame('/api?action', $route->getName());
    }

    #[Test]
    public function backwardCompatibilityWithIndexedArray(): void
    {
        // Old format: indexed array of keys
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'u'],
        );

        // Should be normalized to constraints with null values
        static::assertSame(['action' => null, 'u' => null], $route->getQueryParamConstraints());
        static::assertSame(['action', 'u'], $route->getQueryParamKeys());

        // Should match any values
        static::assertTrue($route->matchesQueryParams(['action' => 'profile', 'u' => '1']));
        static::assertTrue($route->matchesQueryParams(['action' => 'edit', 'u' => '2']));
    }

    #[Test]
    public function constraintsStoredInOptions(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action' => 'profile', 'u' => null],
        );

        $options = $route->getOptions();
        static::assertArrayHasKey('query_params', $options);
        static::assertSame(['action' => 'profile', 'u' => null], $options['query_params']);
    }

    #[Test]
    public function constructorAcceptsQueryParamKeys(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
        );

        static::assertSame(['action', 'type'], $route->getQueryParamKeys());
    }

    #[Test]
    public function delegatesHttpMethodBehavior(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action'],
            ['GET', 'POST'],
        );

        static::assertTrue($route->allowsMethod('GET'));
        static::assertTrue($route->allowsMethod('POST'));
        static::assertFalse($route->allowsMethod('DELETE'));
        static::assertFalse($route->allowsAnyMethod());
    }

    #[Test]
    public function doesNotMatchWhenRequiredKeyMissing(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
        );

        static::assertFalse($route->matchesQueryParams(['action' => 'create']));
    }

    #[Test]
    public function explicitNameIsPreserved(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
            null,
            'custom-route',
        );

        static::assertSame('custom-route', $route->getName());
    }

    #[Test]
    public function getQueryParamConstraints(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action' => 'profile', 'u' => null],
        );

        $constraints = $route->getQueryParamConstraints();
        static::assertSame(['action' => 'profile', 'u' => null], $constraints);
    }

    #[Test]
    public function matchesEmptyQueryParamsWhenNoKeysRequired(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            [],
        );

        static::assertTrue($route->matchesQueryParams([]));
        static::assertTrue($route->matchesQueryParams(['any' => 'param']));
    }

    #[Test]
    public function matchesQueryParamsIsCaseSensitive(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['Action'],
        );

        static::assertFalse($route->matchesQueryParams(['action' => 'create']));
        static::assertTrue($route->matchesQueryParams(['Action' => 'create']));
    }

    #[Test]
    public function matchesQueryParamsWithAllSpecificValues(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action' => 'profile', 'section' => 'settings'],
        );

        // Should match only when both values match
        static::assertTrue($route->matchesQueryParams(['action' => 'profile', 'section' => 'settings']));
        static::assertFalse($route->matchesQueryParams(['action' => 'profile', 'section' => 'other']));
        static::assertFalse($route->matchesQueryParams(['action' => 'other', 'section' => 'settings']));
    }

    #[Test]
    public function matchesQueryParamsWithExactKeys(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
        );

        static::assertTrue($route->matchesQueryParams(['action' => 'create', 'type' => 'user']));
    }

    #[Test]
    public function matchesQueryParamsWithExtraKeys(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action'],
        );

        // Extra keys are allowed, only required keys must be present
        static::assertTrue($route->matchesQueryParams(['action' => 'create', 'extra' => 'value']));
    }

    // Value matching tests

    #[Test]
    public function matchesQueryParamsWithSpecificValue(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action' => 'profile', 'u' => null],
        );

        // Should match when action=profile and u has any value
        static::assertTrue($route->matchesQueryParams(['action' => 'profile', 'u' => '1']));
        static::assertTrue($route->matchesQueryParams(['action' => 'profile', 'u' => '123']));

        // Should NOT match when action has different value
        static::assertFalse($route->matchesQueryParams(['action' => 'edit', 'u' => '1']));
    }

    #[Test]
    public function queryParamKeysStoredInOptions(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['action', 'type'],
        );

        $options = $route->getOptions();
        static::assertArrayHasKey('query_params', $options);
        // Indexed arrays are normalized to associative with null values
        static::assertSame(['action' => null, 'type' => null], $options['query_params']);
    }

    #[Test]
    public function valueConstraintWithNumericValue(): void
    {
        $route = new QueryParamRoute(
            '/api',
            $this->middleware,
            ['page' => '1', 'limit' => null],
        );

        // String '1' should match string '1' exactly
        static::assertTrue($route->matchesQueryParams(['page' => '1', 'limit' => '10']));
        static::assertFalse($route->matchesQueryParams(['page' => '2', 'limit' => '10']));

        // Strict comparison - string '1' does not equal int 1
        static::assertFalse($route->matchesQueryParams(['page' => 1, 'limit' => '10']));
    }

    protected function setUp(): void
    {
        $this->middleware = $this->createStub(MiddlewareInterface::class);
    }
}
